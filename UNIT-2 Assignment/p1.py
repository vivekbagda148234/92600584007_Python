num = int(input("Enter a number : "))

if num>0:
    print("Number is positive")

if num%2 == 0:
    print("Number is even")
else:
    print("Number is odd")

if num>0:
    print("Number is grater than zero")
elif num<0:
    print("Number is less than zero")
else:
    print("Number is zero")
